-- H2 测试库表结构（与 Flyway V1/V3/V4 语义一致，去掉 MySQL 方言）

CREATE TABLE IF NOT EXISTS tb_user (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(64)  NOT NULL,
    password     VARCHAR(128) NOT NULL,
    display_name VARCHAR(64)  NOT NULL,
    role         VARCHAR(32)  NOT NULL,
    email        VARCHAR(128),
    phone        VARCHAR(20),
    status       INT          NOT NULL DEFAULT 1,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_username ON tb_user (username);

CREATE TABLE IF NOT EXISTS warehouse (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(50)  NOT NULL,
    name       VARCHAR(100) NOT NULL,
    type       VARCHAR(50)  NOT NULL,
    address    VARCHAR(255),
    manager    VARCHAR(50),
    phone      VARCHAR(20),
    status     VARCHAR(20)  DEFAULT 'ENABLED',
    capacity   INT,
    created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_warehouse_code ON warehouse (code);

CREATE TABLE IF NOT EXISTS warehouse_zone (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT       NOT NULL,
    code         VARCHAR(50)  NOT NULL,
    name         VARCHAR(100) NOT NULL,
    type         VARCHAR(50)  NOT NULL,
    status       VARCHAR(20)  DEFAULT 'ENABLED',
    created_at   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_zone_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_warehouse_zone_code ON warehouse_zone (warehouse_id, code);

CREATE TABLE IF NOT EXISTS warehouse_location (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id    BIGINT       NOT NULL,
    code       VARCHAR(50)  NOT NULL,
    name       VARCHAR(100),
    spec       VARCHAR(100),
    status     VARCHAR(20)  DEFAULT 'AVAILABLE',
    created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_location_zone FOREIGN KEY (zone_id) REFERENCES warehouse_zone (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_zone_location_code ON warehouse_location (zone_id, code);

CREATE TABLE IF NOT EXISTS sku (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(50)  NOT NULL,
    name       VARCHAR(100) NOT NULL,
    unit       VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);
